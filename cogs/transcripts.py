def _avatar_url(user: discord.abc.User) -> str:
    if user.avatar:
        return str(user.avatar.url)
    return f"https://cdn.discordapp.com/embed/avatars/{int(user.discriminator or 0) % 5}.png"


def _role_colour(member) -> str:
    if isinstance(member, discord.Member) and member.color != discord.Color.default():
        return f"#{member.color.value:06x}"
    return "#dcddde"


def _escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
    )


def _render_embed(embed: discord.Embed) -> str:
    try:
        colour = f"#{embed.colour.value:06x}" if embed.colour and embed.colour.value else "#5865f2"
    except Exception:
        colour = "#5865f2"

    parts = [f'<div class="embed" style="border-left:4px solid {colour}">']

    if embed.author and embed.author.name:
        parts.append(f'<div class="embed-author">{_escape(embed.author.name)}</div>')
    if embed.title:
        parts.append(f'<div class="embed-title">{_escape(embed.title)}</div>')
    if embed.description:
        desc = _escape(embed.description).replace("\n", "<br>")
        parts.append(f'<div class="embed-desc">{desc}</div>')
    for field in embed.fields:
        parts.append(
            f'<div class="embed-field">'
            f'<div class="embed-field-name">{_escape(field.name)}</div>'
            f'<div class="embed-field-value">{_escape(field.value).replace(chr(10), "<br>")}</div>'
            f'</div>'
        )
    if embed.image and embed.image.url:
        parts.append(f'<div class="embed-image"><img src="{_escape(embed.image.url)}" alt="embed image"></div>')
    if embed.footer and embed.footer.text:
        parts.append(f'<div class="embed-footer">{_escape(embed.footer.text)}</div>')

    parts.append("</div>")
    return "\n".join(parts)


