async def save_transcript(channel: discord.TextChannel, guild: discord.Guild) -> str:
    """Returns plain-text transcript (stored in DB)."""
    lines = []
    try:
        async for message in channel.history(limit=500, oldest_first=True):
            ts = message.created_at.strftime("%Y-%m-%d %H:%M:%S UTC")
            author = f"{message.author} ({message.author.id})"
            content = message.content or ""
            embeds = [f"[Embed: {e.title or 'untitled'}]" for e in message.embeds]
            attachments = [f"[Attachment: {a.filename}]" for a in message.attachments]
            parts = [content] + embeds + attachments
            lines.append(f"[{ts}] {author}: {' '.join(p for p in parts if p)}")
    except Exception as e:
        lines.append(f"[Error reading transcript: {e}]")
    return "\n".join(lines)


async def build_html_transcript(
    channel: discord.TextChannel,
    guild: discord.Guild,
    ticket: dict,
    closer: discord.Member,
) -> bytes:
    """Returns HTML transcript as bytes for file upload."""
    messages = []
    try:
        async for msg in channel.history(limit=500, oldest_first=True):
            messages.append(msg)
    except Exception:
        pass

    opener_id = ticket.get("opener_id", "?")
    opener = guild.get_member(int(opener_id)) if opener_id != "?" else None
    claimed_id = ticket.get("claimed_by")
    claimer = guild.get_member(int(claimed_id)) if claimed_id else None
    ticket_type = ticket.get("ticket_type", "trade").title()
    opened_at = ticket.get("created_at", "")[:16].replace("T", " ") if ticket.get("created_at") else ""

    header_lines = [
        f"<b>#{_escape(channel.name)}</b> &nbsp;|&nbsp; {_escape(guild.name)}",
        f"Type: <b>{_escape(ticket_type)}</b> &nbsp;|&nbsp; "
        f"Opened by: <b>{_escape(str(opener)) if opener else opener_id}</b>"
        + (f" &nbsp;|&nbsp; Opened at: <b>{opened_at} UTC</b>" if opened_at else ""),
        f"Closed by: <b>{_escape(str(closer))}</b>"
        + (f" &nbsp;|&nbsp; Claimed by: <b>{_escape(str(claimer))}</b>" if claimer else ""),
        f"Messages captured: <b>{len(messages)}</b>",
    ]

    html = HTML_HEAD.format(title=f"Transcript — #{channel.name}")
    html += '<div class="header">\n'
    html += f'<h1>📄 Transcript — #{_escape(channel.name)}</h1>\n'
    for line in header_lines:
        html += f"<p>{line}</p>\n"
    html += "</div>\n"
    html += '<div class="messages">\n'

    prev_author_id = None

    for msg in messages:
        same_author = (prev_author_id == msg.author.id)
        prev_author_id = msg.author.id

        ts = msg.created_at.astimezone(timezone.utc).strftime("%d/%m/%Y %H:%M")
        colour = _role_colour(msg.author)

        if same_author:
            html += '<div class="msg">\n'
            html += '  <div class="avatar-spacer"></div>\n'
        else:
            html += '<div class="msg with-avatar">\n'
            html += f'  <div class="avatar"><img src="{_escape(_avatar_url(msg.author))}" alt="avatar"></div>\n'

        html += '  <div class="msg-body">\n'

        if not same_author:
            html += (
                f'    <div class="msg-header">'
                f'<span class="username" style="color:{colour}">{_escape(str(msg.author.display_name if isinstance(msg.author, discord.Member) else msg.author.name))}</span>'
                f'<span class="timestamp">{_escape(ts)}</span>'
                f'</div>\n'
            )

        if msg.content:
            html += f'    <div class="content">{_escape(msg.content)}</div>\n'

        for embed in msg.embeds:
            html += f"    {_render_embed(embed)}\n"

        for att in msg.attachments:
            html += f'    <div class="attachment">📎 {_escape(att.filename)}</div>\n'

        html += "  </div>\n</div>\n"

    html += "</div>\n"
    html += HTML_FOOT.format(count=len(messages))

    return html.encode("utf-8")


class Transcripts(commands.Cog):
    def __init__(self, bot):
        self.bot = bot


async def setup(bot):
    await bot.add_cog(Transcripts(bot))
